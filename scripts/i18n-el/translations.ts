// Greek (el) translations for localized fields that live inside array rows
// (plus Services/Products group fields, which can't be saved until their array
// rows have el values).
//
// Shape: a partial document in the el locale. Arrays are written as
// `{ [rowId]: rowPatch }` so each translation is matched to its existing row by
// id — that is what keeps the en values of those rows intact.

type RichText = { root: Record<string, unknown> }

const text = (value: string, format = 0) => ({
  type: 'text',
  text: value,
  format,
  style: '',
  mode: 'normal',
  detail: 0,
  version: 1,
})

const paragraph = (children: unknown[]) => ({
  type: 'paragraph',
  version: 1,
  format: '',
  indent: 0,
  direction: 'ltr',
  textFormat: 0,
  textStyle: '',
  children,
})

const root = (children: unknown[]): RichText => ({
  root: { type: 'root', version: 1, format: '', indent: 0, direction: 'ltr', children },
})

/** Rich text with one paragraph per argument. */
export const rt = (...paragraphs: string[]): RichText =>
  root(paragraphs.map((p) => paragraph([text(p)])))

const item = (titleValue: string, description: string) => ({
  title: titleValue,
  description: rt(description),
})
const tech = (name: string, description: string) => ({ name, description: rt(description) })
const keyword = (value: string) => ({ keyword: value })

